// sandwichHalf collects the two sandwich probes of one side's round.
type sandwichHalf struct {
	round         int
	before, after netip.AddrPort
	sent          bool
}

// sandwichBox bounds the sandwich events waiting for the timer.
const sandwichBox = 8

// Bounds of the server's peer_targets state (one session, each side).
const (
	// maxQueuedAssists bounds the port-mapping and the drift peer_targets
	// waiting for the next go, each: a go is followed by at most
	// TargetsPerRound (4) of them anyway.
	maxQueuedAssists = 4
)

// onAssistLocked handles a client's punch_assist. Only peer_seen
// is accepted, only while punching, for the current or the previous round,
// within the per-round, per-family and rate limits; the server-only fields a
// client filled in are dropped. An accepted peer_seen becomes evidence for
// the next round (SeenFrom, PeerSeenUs) and is forwarded to the peer with
// from set and local removed, unless the forward rate or the peer's queue
// refuses it. Nothing here ends the session.
func (s *Session) onAssistLocked(r int, m *protocol.Assist, now time.Duration) effects {
	st := &s.st
	ctr := &st.ctr
	switch {
	case s.ablate.NoAssistRelay || st.state != StatePunching:
		ctr.AssistDropped++
		return effects{}
	case m.Kind != protocol.AssistPeerSeen:
		ctr.AssistRejected++
		return effects{}
	}
	var stripped bool
	if *m, stripped = m.StripServerFields(); stripped {
		ctr.AssistRejected++
	}
	k := int(m.Round)
	if k != st.rounds.round && k != st.rounds.round-1 {
		ctr.AssistRejected++
		return effects{}
	}
	fi := m.Family.Index()
	l := st.links[r]
	if lim := s.c.set.limits.AssistPerRound; lim >= 0 && st.rounds.cur.assists[r][fi] >= lim {
		ctr.AssistDropped++
		return effects{}
	}
	if ok, _ := l.assistIn.take(s.at(now), 1); !ok {
		ctr.AssistDropped++
		return effects{}
	}
	st.rounds.cur.assists[r][fi]++
	addSeen(&st.rounds.ev.SeenFrom[r], m.Remote)
	s.addMappingLocked(1-r, k, m.Remote)
	st.rounds.ev.PeerSeenUs[1-r] = true

	p := st.links[1-r]
	if p == nil || p.dead || st.gone[1-r] {
		ctr.AssistDropped++
		return effects{}
	}
	if ok, _ := p.relayTo.take(s.at(now), 1); !ok {
		ctr.AssistDropped++
		return effects{}
	}
	if err := p.send(m.Relayed(roleOf(r))); err != nil {
		ctr.AssistDropped++
		return effects{}
	}
	ctr.AssistForwarded++
	return effects{}
}

// sendTargetsLocked sends side p a peer_targets assist, generated by the
// server (sandwich, inject, drift, portmap): every target and the window
// IP pass admission against the other side's addresses, at most 16 targets
// and a 64-port window, at most TargetsPerRound per side and round. The
// assist is cut to what the side may still be charged (trimPushLocked) and
// charged when sent (chargePushLocked); with nothing left it is refused with
// ErrBusy (dimension packets).
func (s *Session) sendTargetsLocked(p int, a protocol.Assist, now time.Duration) error {
	st := &s.st
	l := st.links[p]
	switch {
	case st.state != StatePunching:
		return argumentError("not_punching", "the session is not punching")
	case l == nil || l.dead || st.gone[p]:
		return ErrSessionDone
	}
	if lim := s.c.set.limits.TargetsPerRound; lim >= 0 && st.rounds.cur.targets[p] >= lim {
		return busyError("peer_targets", time.Second)
	}
	q := 1 - p
	out := protocol.Assist{SessionID: s.id, From: protocol.RoleServer, Kind: protocol.AssistPeerTargets,
		Round: uint8(st.rounds.round), Family: a.Family, Source: a.Source, Meta: a.Meta}
	if !a.Family.Valid() {
		return argumentError("family", "unknown family %q", a.Family)
	}
	if err := out.Validate(); err != nil {
		// Only Meta, the caller's pass-through, can be malformed here: it
		// would fail the write as if the link were busy.
		return argumentError("meta", "%v", err)
	}
	for _, t := range a.Targets {
		if len(out.Targets) < protocol.MaxStageTargets && s.admitDirectLocked(q, a.Family, t, st.rounds.round, now) != admitRejected {
			out.Targets = append(out.Targets, t)
		}
	}
	if w := a.Window; w != nil && w.Lo > 0 && w.Hi >= w.Lo && s.admitIPLocked(q, a.Family, w.IP, st.rounds.round, now) {
		win := *w
		win.Hi = uint16(min(int(win.Hi), int(win.Lo)+protocol.MaxPortWindowWidth)) // Lo + 63 may pass 65535
		out.Window = &win
	}
	if len(out.Targets) == 0 && out.Window == nil {
		return argumentError("no_admitted_target", "no target passed admission")
	}
	n := s.trimPushLocked(p, &out, now)
	if n == 0 {
		st.ctr.AssistDropped++
		return busyError("packets", time.Second)
	}
	if err := l.send(out); err != nil {
		st.ctr.AssistDropped++
		return busyError("link", time.Second)
	}
	s.chargePushLocked(p, out.Family.Index(), n, now)
	st.rounds.cur.targets[p]++
	st.ctr.PeerTargets++
	s.c.emit(Event{Kind: EvPeerTargets, At: s.at(now), SessionID: s.id, Role: roleOf(p), Round: st.rounds.round,
		Labels: s.labels, Data: PeerTargetsData{Source: out.Source, Targets: out.Targets, Window: out.Window}})
	return nil
}

// trimPushLocked cuts a peer_targets assist for side p to what the side may
// still be charged: protocol.PushPackets a target or window port within the session
// budget and the key's quota, and at most protocol.MaxPushPerRound a family and round
// (the client's cap). The window narrows around its middle. It returns the
// targets and ports left.
func (s *Session) trimPushLocked(p int, a *protocol.Assist, now time.Duration) int {
	room := min(s.budgetLeftLocked(p, now)/protocol.PushPackets, protocol.MaxPushPerRound-s.st.rounds.cur.pushed[p][a.Family.Index()])
	room = max(room, 0)
	a.Targets = a.Targets[:min(len(a.Targets), room)]
	n := len(a.Targets)
	if w := a.Window; w != nil {
		width, keep := int(w.Hi-w.Lo)+1, room-n
		switch {
		case keep <= 0:
			a.Window = nil
			width = 0
		case width > keep:
			w.Lo += uint16((width - keep) / 2)
			w.Hi = w.Lo + uint16(keep-1)
			width = keep
		}
		n += width
	}
	return n
}

// chargePushLocked charges side p for n pushed targets and window ports of
// family index fi: protocol.PushPackets each against the session budget and the key's
// quota, the ports against the 10 s window, and the packets as push credit, which
// the audit pays out whichever round the client sends them in.
func (s *Session) chargePushLocked(p, fi, n int, now time.Duration) {
	st := &s.st
	packets := n * protocol.PushPackets
	st.audit.granted[p] += packets
	st.audit.credit[p] += packets
	st.rounds.cur.pushed[p][fi] += n
	st.rounds.recentPorts[st.rounds.cur.n][p] += n
	s.c.limiter.grant(s.at(now), p, s.keys[p], packets)
}

// Inject sends the target side targets the caller learned elsewhere, as
// peer_targets{source: inject}: only while punching, through the same
// admission and the same per-round limit as the server's own targets. Only
// a.Family, a.Targets, a.Window and a.Meta are used. Errors: ErrInvalidRole,
// ErrSessionDone, ErrBusy (round limit, no budget left for the targets, or
// the link's queue), and a *protocol.ValidationError with Reason
// invalid_argument (not punching, an unknown family or a malformed Meta,
// nothing admitted).
func (s *Session) Inject(target protocol.Role, a protocol.Assist) error {
	p, ok := roleIndex(target)
	if !ok {
		return ErrInvalidRole
	}
	now := s.c.set.clock.Now()
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.st.state == StateClosed {
		return ErrSessionDone
	}
	a.Source = protocol.TargetsInject
	return s.sendTargetsLocked(p, a, s.since(now))
}

// onSandwich is the natprobe sink of sandwich probes: a bounded append
// and an immediate timer, so the natprobe reader never waits; the timer
// callback computes the window.
func (s *Session) onSandwich(ev nat.SandwichEvent) {
	s.mu.Lock()
	defer s.mu.Unlock()
	st := &s.st
	if st.state != StatePunching && !st.refresh.pending || len(st.sand.box) >= sandwichBox {
		return
	}
	st.sand.box = append(st.sand.box, ev)
	s.timer.Reset(0)
}

// sandwichLocked turns the queued sandwich probes into windows: once
// a side's two probes of the current round are in, the ports between them,
// cut to 64 around the middle, on that side's verified IP, go to the other
// side as peer_targets{source: sandwich}. Probes are matched per family —
// the family of the address natprobe saw — so the two families of a
// dual-stack side each bracket their own punches.
func (s *Session) sandwichLocked(now time.Duration) {
	st := &s.st
	box := st.sand.box
	st.sand.box = nil
	for _, ev := range box {
		if ev.Phase == nat.RefreshFirst || ev.Phase == nat.RefreshSecond {
			s.refreshEventLocked(ev, now)
			continue
		}
		x, ok := roleIndex(ev.Role)
		fi := protocol.FamilyOf(ev.Observed.Addr()).Index()
		if !ok || int(ev.Round) != st.rounds.round || !st.rounds.cur.sandwich[x][fi] {
			continue
		}
		h := &st.sand.half[x][fi]
		if h.round != st.rounds.round {
			*h = sandwichHalf{round: st.rounds.round}
		}
		switch ev.Phase {
		case nat.SandwichBefore:
			h.before = ev.Observed
		case nat.SandwichAfter:
			h.after = ev.Observed
		}
		if h.sent || !h.before.IsValid() || !h.after.IsValid() || h.before.Addr() != h.after.Addr() {
			continue
		}
		lo, hi := sandwichWindow(h.before.Port(), h.after.Port())
		if lo == 0 {
			continue
		}
		h.sent = true
		ip := h.before.Addr()
		_ = s.sendTargetsLocked(1-x, protocol.Assist{Family: protocol.FamilyOf(ip), Source: protocol.TargetsSandwich,
			Window: &protocol.PortWindow{IP: ip, Lo: lo, Hi: hi}}, now)
	}
}

// sandwichWindow is the ports strictly between two sandwich probes' mapped
// ports, at most 64 of them around the middle; lo is 0 when there is none.
func sandwichWindow(a, b uint16) (lo, hi uint16) {
	lo32, hi32 := int(min(a, b))+1, int(max(a, b))-1
	if hi32 < lo32 {
		return 0, 0
	}
	if hi32-lo32 > protocol.MaxPortWindowWidth {
		mid := (int(a) + int(b)) / 2
		lo32 = max(mid-protocol.MaxPortWindowWidth/2, 1)
		hi32 = lo32 + protocol.MaxPortWindowWidth
	}
	return uint16(lo32), uint16(hi32)
}

// observeDrift reads natprobe's moved primary mappings of both sides
// (ProbeHandle.Drifted) while punching — the handle stays open until the
// first confirmation. It runs outside the lock; takeDriftLocked decides
// what to push.
func (s *Session) observeDrift() [2][]nat.Drift {
	var out [2][]nat.Drift
	s.mu.Lock()
	open := s.st.state == StatePunching
	s.mu.Unlock()
	if !open || s.handle == nil {
		return out
	}
	for r := range out {
		out[r] = s.handle.Drifted(roleOf(r))
	}
	return out
}

// takeDriftLocked turns moved primary mappings into peer_targets{source:
// drift} for the other side, sent with the next go (≤ maxQueuedAssists a
// side, ≤ protocol.MaxDrifted a session). A new port on an IP the side was verified
// on is taken as it is: the IP passed the cookie check at the summary. A
// mapping on another IP is taken only when the side echoed the slot's
// cookie for exactly this value in a round_result remap (Drift.EchoedBy) — the return-path
// check of the summary's endpoints — and the IP is public; it then
// joins the side's verified IPs. A mapping the peer already has in
// its summary is not pushed again. Under the NoAssistRelay ablation nothing
// is taken: the clients drop every assist, so the peer would never admit a
// new IP that later plans aim at.
func (s *Session) takeDriftLocked(drift [2][]nat.Drift) {
	st := &s.st
	if s.ablate.NoAssistRelay {
		return
	}
	for r, obs := range drift {
		for _, d := range obs {
			a, fam := d.Observed, d.Family
			switch {
			case !slices.Contains(st.plan.cls.Families, fam) || st.adm.pair.Unverified[fam],
				st.rounds.drifted[a] || len(st.rounds.drifted) >= protocol.MaxDrifted || len(st.rounds.pending[1-r]) >= maxQueuedAssists,
				hasEndpoint(st.plan.views[r], fam, a):
				continue
			case st.adm.knownIP(r, fam, a.Addr()):
			case d.EchoedBy(st.rounds.remaps[r][fam.Index()]) && !netaddr.Private(a.Addr()):
				st.adm.verified[r][fam] = append(st.adm.verified[r][fam], a.Addr())
			default:
				continue
			}
			if st.rounds.drifted == nil {
				st.rounds.drifted = map[netip.AddrPort]bool{}
			}
			st.rounds.drifted[a] = true
			st.rounds.pending[1-r] = append(st.rounds.pending[1-r], protocol.Assist{Family: fam, Source: protocol.TargetsDrift,
				Targets: []netip.AddrPort{a}})
		}
	}
}

// adoptDriftLocked makes a pushed drifted mapping of side r the planner's
// first endpoint of its family, where it supersedes the socket's earlier
// mapping, and a punch-time mapping sample of round k, the round it was
// observed in: the plans from the next round on aim at it. It runs
// once the push is written, not when the drift is taken: the peer admits a
// new IP only from the push on, and the go of the round the push goes with
// was planned before.
func (s *Session) adoptDriftLocked(r int, fam protocol.Family, a netip.AddrPort, k int) {
	s.prependPlannerEndpointLocked(r, fam, protocol.Endpoint{Addr: a, Source: protocol.EndpointServer,
		Socket: nat.SocketID(fam, nat.IndexPrimary), Verified: true})
	s.addMappingLocked(r, k, a)
}

// hasEndpoint reports whether a is an endpoint of family fam in view v.
func hasEndpoint(v protocol.PeerView, fam protocol.Family, a netip.AddrPort) bool {
	fv, ok := familyView(v, fam)
	return ok && slices.ContainsFunc(fv.Endpoints, func(e protocol.Endpoint) bool { return e.Addr == a })
}
